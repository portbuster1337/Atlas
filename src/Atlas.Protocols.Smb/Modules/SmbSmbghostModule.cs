	public override async Task RunAsync(AtlasModuleContext<Smb2Client> ctx, CancellationToken cancellationToken)
	{
		try
		{
			using var tcp = new TcpClient();
			await tcp.ConnectAsync(ctx.Host, 445, cancellationToken).ConfigureAwait(false);
			using var stream = tcp.GetStream();
			await stream.WriteAsync(Negotiate, cancellationToken).ConfigureAwait(false);
			byte[] nb = new byte[4];
			await ReadExactAsync(stream, nb, cancellationToken).ConfigureAwait(false);
			int len = (nb[0] << 24) | (nb[1] << 16) | (nb[2] << 8) | nb[3];
			if (len <= 0 || len > 65536) throw new InvalidOperationException("bad negotiate response length");
			byte[] res = new byte[len];
			await ReadExactAsync(stream, res, cancellationToken).ConfigureAwait(false);
			if (len >= 72 && res[68] == 0x11 && res[69] == 0x03 && res[70] == 0x02 && res[71] == 0x00)
				AtlasConsole.Success($"{ctx.Host}:445", "(smbghost) Potentially VULNERABLE to SMBGhost (dialect 3.1.1 + compression offered)");
			else
				AtlasConsole.Info($"{ctx.Host}:445", "(smbghost) Not vulnerable (no 3.1.1+compression negotiate)");
		}
		catch (Exception ex)
		{
			AtlasConsole.Fail($"{ctx.Host}:445", $"(smbghost) Failed: {ex.Message}");
		}
	}

	private static async Task ReadExactAsync(NetworkStream stream, byte[] buf, CancellationToken ct)
	{
		int off = 0;
		while (off < buf.Length)
		{
			int n = await stream.ReadAsync(buf.AsMemory(off), ct).ConfigureAwait(false);
			if (n == 0) throw new EndOfStreamException("connection closed");
			off += n;
		}
	}
